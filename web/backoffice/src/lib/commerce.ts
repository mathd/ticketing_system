// The back office's commerce client: one read (TKT-193) and one write (TKT-194).
//
// The read goes through the gateway like everything else. The refund does NOT —
// see refundOrder.
import {
  GATEWAY_URL,
  type Read,
  boolean,
  currency,
  fetchUpstream,
  nonNegativeWholeNumber,
  positiveWholeNumber,
  readJson,
  required,
  responseObject,
  sameIdentity,
  withUpstreamDeadline,
  uuid,
} from './upstream';

const commerce = (path: string) => `${GATEWAY_URL}/api/commerce${path}`;

export type OrderState = { orderId: string; status: string };

/** Commerce's order state: `{order_id, status}` and, by contract, nothing else. */
export function getOrderState(orderId: string): Promise<Read<OrderState>> {
  return readJson(commerce(`/orders/${encodeURIComponent(orderId)}`), (body) => {
    const b = responseObject(body, 'order state');
    const got = uuid(b.order_id, 'order_id');
    sameIdentity(got, orderId, 'order_id');
    return { orderId: got, status: required(b.status, 'status') };
  });
}

// ---------------------------------------------------------------------------
// The staff refund (TKT-194).
//
// DIRECT to commerce, not through the gateway. The gateway edge-denies every
// `/api/<svc>/internal/` route by construction (ADR-002: the route table is the
// security boundary), and adding a named exception would publish a
// money-moving endpoint to the public internet behind one bearer token — while
// granting this process nothing it does not already have, since it can already
// open a socket to commerce on the container network. The credential is the
// boundary here; the network path is not. Access reaches commerce's internal
// delivery-email read exactly this way.

const COMMERCE_URL = process.env.COMMERCE_URL ?? 'http://localhost:8082';

/**
 * The back office's commerce credential (TKT-194, ADR-042 as amended).
 *
 * Refuses to equal the catalog credential. Two credentials with different blast
 * radii are only two credentials if they hold different values, and equality
 * would mean a leak of the catalog token — which authors events — became a leak
 * of the token that refunds money. Commerce makes the same check against
 * `INTERNAL_SERVICE_TOKEN` at startup; this is the pair only this process holds,
 * so it is the pair only this process can compare (credentials.mjs).
 *
 * Read through a function rather than a module constant so a missing value
 * fails on the first refund with a message naming the variable.
 */
function commerceStaffCredential(): string {
  const token = process.env.COMMERCE_STAFF_WRITE_TOKEN;
  if (!token) {
    throw new Error(
      'COMMERCE_STAFF_WRITE_TOKEN is not set: the back office cannot refund. ' +
        'It is generated by `make up` and supplied by compose.',
    );
  }
  return token;
}

export type Refund = {
  refundId: string;
  orderId: string;
  quantity: number;
  amount: number;
  currency: string;
  refundStatus: 'none' | 'partial' | 'full';
  refundedQuantity: number;
  refundedAmount: number;
  replay: boolean;
  ticketsVoided: boolean;
  capacityReturned: boolean;
};

/**
 * Why three failure kinds and not two.
 *
 * `not-found` and `refused` are decided: commerce looked and said no, so the
 * page can state it. `ambiguous` is a 5xx or a success whose body we could not
 * verify — the refund **may have happened**, and the only honest thing to render
 * is "retry this exact request", with the idempotency key preserved so the retry
 * is a replay rather than a second refund.
 *
 * `abandoned` (TKT-525 S2) is a decided refusal with one specific meaning: an
 * operator recorded the refund behind this key as abandoned, so nothing will
 * ever move under it. Commerce sends it as a 409 with `code: refund_abandoned`,
 * and only that combination is read as this kind.
 */
export type RefundOutcome =
  | { ok: true; value: Refund }
  | { ok: false; kind: 'not-found' | 'refused' | 'ambiguous' | 'abandoned'; message: string };

export type RefundRequest = {
  orderId: string;
  quantity: number;
  reason: string;
  /** From the session. Never from the form — see COS-5. */
  actor: string;
  /**
   * The session's organizer assertion (TKT-287). Commerce verifies it with
   * catalog's public key and takes the organizer from it; the request body names
   * no organizer at all. Server-side only — never rendered into a page.
   */
  assertion: string;
  idempotencyKey: string;
};

export async function refundOrder(req: RefundRequest): Promise<RefundOutcome> {
  // OUTSIDE the try. A missing credential is a configuration defect, and
  // reporting it as an ambiguous commerce outage would tell the operator to
  // retry a request that can never succeed (ai-review pass 1).
  const credential = commerceStaffCredential();
  try {
    return await withUpstreamDeadline(async (signal) => {
      const res = await fetchUpstream(
        `${COMMERCE_URL}/internal/orders/${encodeURIComponent(req.orderId)}/refunds`,
        {
          method: 'POST',
          headers: {
            'content-type': 'application/json',
            'Idempotency-Key': req.idempotencyKey,
            'X-Commerce-Staff-Write-Token': credential,
            'X-Catalog-Organizer-Assertion': req.assertion,
          },
          body: JSON.stringify({
            quantity: req.quantity,
            actor: req.actor,
            reason: req.reason,
          }),
          signal,
        },
      );

      const message = await commerceMessage(res);
      if (res.status === 404) return { ok: false, kind: 'not-found', message };
      if (res.status === 409 && (await commerceCode(res)) === 'refund_abandoned') {
        return { ok: false, kind: 'abandoned', message: ABANDONED_REFUND_MESSAGE };
      }
      if (res.status === 400 || res.status === 409) {
        return { ok: false, kind: 'refused', message };
      }
      if (!res.ok) return { ok: false, kind: 'ambiguous', message };

      try {
        const b = responseObject(await res.json(), 'refund');
        const orderId = uuid(b.order_id, 'order_id');
        sameIdentity(orderId, req.orderId, 'order_id');
        const status = required(b.refund_status, 'refund_status');
        if (status !== 'none' && status !== 'partial' && status !== 'full') {
          throw new Error('refund_status is outside the contract enum');
        }
        const quantity = positiveWholeNumber(b.quantity, 'quantity');
        if (quantity > 50) throw new Error('quantity is above the contract maximum');
        const refundedQuantity = nonNegativeWholeNumber(
          b.refunded_quantity,
          'refunded_quantity',
        );
        if (refundedQuantity > 50) {
          throw new Error('refunded_quantity is above the contract maximum');
        }
        return {
          ok: true,
          value: {
            refundId: uuid(b.refund_id, 'refund_id'),
            orderId,
            // Commerce refund amounts inherit the full int64 order-total range.
            // This number-based console has a narrower capability and treats an
            // amount it cannot represent exactly as an ambiguous result.
            quantity,
            amount: nonNegativeWholeNumber(b.amount, 'amount'),
            currency: currency(b.currency, 'currency'),
            refundStatus: status,
            refundedQuantity,
            refundedAmount: nonNegativeWholeNumber(b.refunded_amount, 'refunded_amount'),
            replay: boolean(b.replay, 'replay'),
            ticketsVoided: boolean(b.tickets_voided, 'tickets_voided'),
            capacityReturned: boolean(b.capacity_returned, 'capacity_returned'),
          },
        };
      } catch {
        // A 200 we cannot verify is not a failure to refund. Commerce answered
        // 200, but this console cannot describe the result, so it is ambiguous.
        return {
          ok: false,
          kind: 'ambiguous',
          message: 'Commerce accepted the refund but returned something this console cannot read.',
        };
      }
    });
  } catch {
    // The request may have reached commerce and been applied. Never "no refund
    // happened". A refused redirect lands here too (ADR-088): the first hop
    // received the POST, and the redirect target's answer is not Commerce's.
    return { ok: false, kind: 'ambiguous', message: 'Commerce could not be reached.' };
  }
}

/**
 * What the page says when commerce settles a refund key as abandoned. It does
 * not say that nothing reached the payment provider: a request admitted before
 * the abandonment can have reached it (ADR-087 §13).
 */
export const ABANDONED_REFUND_MESSAGE =
  'An operator recorded this refund as abandoned. ' +
  'If the buyer is still owed, submit a new refund below.';

/**
 * Whether commerce's staff order detail confirms a COMMITTED abandonment of the
 * refund behind exactly this organizer, order and idempotency key (TKT-525,
 * ADR-087).
 *
 * The saved retry keeps the original request, actor included, because commerce
 * fingerprints the key over it. Another staff member's retry of that key is a
 * generic 409, not `refund_abandoned`, so the refund write cannot tell this page
 * that the key is settled. This read can: it is scoped by the session's verified
 * organizer assertion, not by the actor.
 *
 * Fails closed. Any answer other than a readable 200 that names this order, this
 * organizer and an abandoned refund under this key is `false`, and the caller
 * keeps the saved retry. A redirect is refused before its body is read
 * (ADR-088), so a redirect target cannot confirm anything.
 */
export async function confirmsAbandonedRefund(req: {
  orderId: string;
  organizerId: string;
  idempotencyKey: string;
  /** The session's organizer assertion. Server-side only. */
  assertion: string;
}): Promise<boolean> {
  const credential = commerceStaffCredential();
  try {
    return await withUpstreamDeadline(async (signal) => {
      const res = await fetchUpstream(`${COMMERCE_URL}/internal/orders/${encodeURIComponent(req.orderId)}`, {
        headers: {
          'X-Commerce-Staff-Write-Token': credential,
          'X-Catalog-Organizer-Assertion': req.assertion,
        },
        signal,
      });
      if (res.status !== 200) return false;
      const b = responseObject(await res.json(), 'staff order detail');
      // Case-insensitive, as everywhere else on this console: the form accepts an
      // uppercase UUID, and commerce answers in canonical lowercase (R3-2). The key
      // below stays an exact match. A mismatch throws, and the catch answers false.
      sameIdentity(uuid(b.order_id, 'order_id'), req.orderId, 'order_id');
      sameIdentity(uuid(b.organizer_id, 'organizer_id'), req.organizerId, 'organizer_id');
      if (!Array.isArray(b.refunds)) return false;
      return b.refunds.some((f: unknown) => {
        if (typeof f !== 'object' || f === null) return false;
        const r = f as Record<string, unknown>;
        return r.idempotency_key === req.idempotencyKey && r.abandoned === true;
      });
    });
  } catch {
    return false;
  }
}

/** Commerce's machine-readable refusal code, or undefined. */
async function commerceCode(res: Response): Promise<string | undefined> {
  try {
    const b = responseObject(await res.clone().json(), 'commerce error');
    return typeof b.code === 'string' ? b.code : undefined;
  } catch {
    return undefined;
  }
}

async function commerceMessage(res: Response): Promise<string> {
  try {
    const b = responseObject(await res.clone().json(), 'commerce error');
    if (typeof b.error === 'string' && b.error !== '') return b.error;
  } catch {
    /* fall through to the generic line */
  }
  return `Commerce answered ${res.status}.`;
}
