// --- Staff sign-in (TKT-190 / US-B1) ---

/** Who is signed in, and the credential that says which organizer for. */
export interface StaffPrincipalDto {
  staffId: string;
  organizerId: string;
  role: StaffRole;
  /**
   * Catalog's signed organizer statement (TKT-245). Goes straight into the
   * server-side session and is forwarded on writes; it is never rendered.
   */
  organizerAssertion: string;
}

/**
 * Verify a staff credential. Returns null for "those credentials are wrong" —
 * an expected answer to a sign-in attempt, not an exceptional one — and throws
 * for anything else, so an outage can never be rendered as a bad password.
 *
 * Goes through the gateway like every other call in this file. The catalog's
 * authenticate operation is public precisely so this stays true: reaching an
 * internal-token endpoint would mean shipping the shared service credential into
 * the back-office container, and that one token also opens commerce's refunds
 * and inventory's operational holds (ADR-042).
 */
export async function authenticateStaff(
  identifier: string,
  password: string,
): Promise<StaffPrincipalDto | null> {
  const res = await fetch(catalog('/staff/authenticate'), {
    method: 'POST',
    // Guarded like every other unsafe operation (TKT-191). ADR-042 originally
    // made this endpoint public to avoid putting the SHARED service token in
    // this process; a catalog-only credential removes that objection, and
    // leaving it unguarded would mean an exception list inside a fail-closed
    // scheme.
    headers: writeHeaders(),
    // In the body, never the URL: a query string lands in access logs, proxy
    // logs and browser history.
    body: JSON.stringify({ identifier, password }),
  });
  if (res.status === 401) {
    return null;
  }
  if (!res.ok) {
    throw await parseError(res);
  }
  const body = (await res.json()) as {
    staff_id: string;
    organizer_id: string;
    role: string;
    organizer_assertion: string;
  };
  if (!isRecognisedRole(body.role)) {
    // Catalog validates the stored role too, so reaching this means the contract
    // and this client disagree about the vocabulary — a deployment skew. Refuse
    // rather than mint a session carrying a role the matrix cannot classify:
    // fail-closed at every layer that handles a role is the whole design.
    throw new Error(`catalog returned an unrecognised staff role`);
  }
  // An empty assertion means catalog has no signing key configured (TKT-245).
  // Refuse the sign-in rather than mint a session that cannot write: every
  // subsequent write would 401, which reads to the staff member as "my password
  // works but nothing I do saves" — the least diagnosable failure available.
  if (!body.organizer_assertion) {
    throw new Error('catalog returned no organizer assertion; it is running without a signing key');
  }
  return {
    staffId: body.staff_id,
    organizerId: body.organizer_id,
    role: body.role,
    organizerAssertion: body.organizer_assertion,
  };
}

// --- Event authoring (TKT-192 / US-B3) ---
//
// Four thin wrappers over postCatalog, which already attaches the staff-write
// credential (TKT-191) and turns a non-2xx into a CatalogApiError carrying
// catalog's own {error} message. The builder page surfaces that message
// verbatim, so a refusal catalog decides (ADR-018) reads as a sentence rather
// than a status code.
//
// The organizer is a parameter on every one of these, never a default: it comes
// from the session (TKT-190), and a default here is how one organizer's staff
// would author into another's tenant.

export type Event = components['schemas']['Event'];
export type Performance = components['schemas']['Performance'];
export type TicketType = components['schemas']['TicketType'];
export type LocalizedStringDto = components['schemas']['LocalizedString'];

export function createEvent(assertion: string, name: LocalizedStringDto): Promise<Event> {
  return postCatalog<Event>('/events', assertion, { name });
}

export function createPerformance(
  assertion: string,
  input: { eventId: string; venueId: string; startsAt: string; timezone: string },
): Promise<Performance> {
  return postCatalog<Performance>('/performances', assertion, {
    event_id: input.eventId,
    venue_id: input.venueId,
    // RFC 3339 with an explicit offset, and the IANA zone alongside it. A
    // `datetime-local` value carries no zone, and converting one in the SERVER's
    // zone would shift every slot for any organizer who is not sitting next to
    // the server — silently, and only for them.
    starts_at: input.startsAt,
    timezone: input.timezone,
  });
}

export function createTicketType(
  assertion: string,
  input: { performanceId: string; name: LocalizedStringDto; amount: number; currency: string },
): Promise<TicketType> {
  return postCatalog<TicketType>('/ticket-types', assertion, {
    performance_id: input.performanceId,
    name: input.name,
    // Integer minor units + ISO code, parsed as such (ADR-001). Nothing on this
    // path has ever been a float.
    price: { amount: input.amount, currency: input.currency },
  });
}

/**
 * Publish a draft slot. Catalog owns the decision (ADR-018): a grouped festival
 * day refuses its own publish, an archived slot refuses the transition, and a
 * slot with no ticket type is refused as not sellable. Each arrives here as a
 * CatalogApiError whose message is catalog's own.
 */
export function publishPerformance(performanceId: string): Promise<Performance> {
  // No assertion: a path-id transition, the follow-up slice (ADR-058).
  return postCatalog<Performance>(
    `/performances/${encodeURIComponent(performanceId)}/publish`,
    '',
    null,
  );
}

// --- The sales-channel registry (TKT-236 / TKT-235). ------------------------
//
// Writes go through the gateway like every other catalog write. The OPERATOR
// READ does not, and that asymmetry is the ticket's one auth decision:
//
// The page must show DISABLED channels, and only `GET /internal/channels`
// returns those — `/public/channels` is enabled-only by design. The gateway
// edge-denies every `/api/<svc>/internal/` route by construction (ADR-002), so
// the read goes DIRECT to catalog on the container network, exactly as the
// staff refund reaches commerce (TKT-194, commerce.ts).
//
// It authenticates with the catalog staff-write credential this process ALREADY
// holds — never `X-Internal-Token`, which the back office is deliberately denied
// (compose.yaml) and which `api.test.ts` pins that it never sends. Catalog
// accepts that credential on this one method+path and nothing else (ADR-053,
// `staffMayReadOperatorChannels`).
//
// NOT tenant isolation. Callers pass the organizer from their SESSION and must
// never take one from the request; catalog authenticates this process, not the
// staff member behind it (ADR-021).

export type Channel = components['schemas']['Channel'];
export type ChannelKind = components['schemas']['ChannelKind'];

// Catalog's host on the container network. Only used for the operator read; every
// other call in this file goes through the gateway.
const CATALOG_URL = process.env.CATALOG_URL ?? 'http://localhost:8081';

/**
 * The organizer's channels, enabled AND disabled, for the admin page.
 *
 * `organizerId` is required rather than defaulted: this read is the one place a
 * caller could quietly show another tenant's configuration, so the call site has
 * to name whose channels it wants — and every call site takes it from the
 * session.
 */
export async function listChannelsForOperator(assertion: string): Promise<Channel[]> {
  // No organizer in the URL (TKT-245). This read returns every channel of an
  // organizer — ids, codes and disabled rows that appear nowhere public — and
  // naming the tenant in a query string is exactly the enumeration ADR-053
  // recorded. Catalog takes it from the assertion instead.
  const url = `${CATALOG_URL}/internal/channels`;
  const res = await fetch(url, {
    headers: {
      'X-Catalog-Staff-Write-Token': staffWriteCredential(),
      'X-Catalog-Organizer-Assertion': assertion,
    },
  });
  if (!res.ok) {
    throw await parseError(res);
  }
  const body = (await res.json()) as { channels?: Channel[] };
  // Defensive: a contract-shaped body with no array must not become `undefined`
  // and crash the page's map. The operator read is hand-mounted and therefore
  // outside catalog's response validation (ADR-009), so nothing upstream
  // guarantees the key is present.
  return body.channels ?? [];
}

export function createChannel(
  assertion: string,
  input: { code: string; displayName: string; kind: ChannelKind; enabled?: boolean },
): Promise<Channel> {
  return postCatalog<Channel>('/channels', assertion, {
    code: input.code,
    display_name: input.displayName,
    kind: input.kind,
    ...(input.enabled === undefined ? {} : { enabled: input.enabled }),
  });
}

/**
 * Update a channel's display name, kind and enabled flag.
 *
 * FULL REPLACEMENT, scoped to the organizer the ASSERTION names (TKT-245) —
 * which the caller can no longer choose at all. `code` is required in the body even
 * though it cannot change: catalog compares it against the stored code and answers 409 on a
 * mismatch, so the caller states which channel it believes it is updating
 * (TKT-235). Every field must be sent — omitting `enabled` would not "leave it
 * alone", it would send `false`.
 */
export async function updateChannel(
  assertion: string,
  channelId: string,
  input: { code: string; displayName: string; kind: ChannelKind; enabled: boolean },
): Promise<Channel> {
  const res = await fetch(catalog(`/channels/${encodeURIComponent(channelId)}`), {
    method: 'PUT',
    headers: writeHeaders(assertion),
    body: JSON.stringify({
      // The channel id still comes from a form field, and an id is still not an
      // authorization boundary — but the tenant it is checked against now comes
      // from the assertion rather than the body, so catalog refuses another
      // organizer's channel with 404 whatever the caller claims (TKT-245).
      code: input.code,
      display_name: input.displayName,
      kind: input.kind,
      enabled: input.enabled,
    }),
  });
  if (!res.ok) {
    throw await parseError(res);
  }
  return (await res.json()) as Channel;
}
