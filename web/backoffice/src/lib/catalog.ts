// CatalogApiError carries the catalog's parsed { error } message and HTTP status
// (emulating the storefront's UpstreamError) so the UI can show an actionable
// message — e.g. the TKT-104 pinning-contract rejection — instead of a bare
// status code.
export class CatalogApiError extends Error {
  constructor(
    public readonly status: number,
    message: string,
  ) {
    super(message);
    this.name = 'CatalogApiError';
  }
}

/**
 * The back office's credential for catalog writes (TKT-191, ADR-042). Catalog
 * authenticates the DEPUTY — it knows the caller is this process; which staff
 * member may drive which write is decided here, by the session gate (roles are
 * TKT-197).
 *
 * Read through a function rather than a module constant so a missing value
 * fails on the first write with a message naming the variable, instead of
 * silently sending `undefined` and surfacing as catalog's deliberately
 * uninformative 401 — which is indistinguishable from a wrong password on the
 * sign-in path.
 */
function staffWriteCredential(): string {
  const token = process.env.CATALOG_STAFF_WRITE_TOKEN;
  if (!token) {
    throw new Error(
      'CATALOG_STAFF_WRITE_TOKEN is not set: the back office cannot write to catalog. ' +
        'It is generated by `make up` and supplied by compose.',
    );
  }
  return token;
}

/**
 * Headers for every catalog write. One helper, so no call site can forget.
 *
 * `assertion` is the session's organizer assertion (TKT-245). It is REQUIRED on
 * every write except the sign-in that issues one — catalog reads the organizer
 * from it and accepts none in a request body — so it is a positional parameter
 * rather than an option: a call site that forgets it does not compile.
 */
function writeHeaders(assertion?: string): Record<string, string> {
  const headers: Record<string, string> = {
    'content-type': 'application/json',
    'X-Catalog-Staff-Write-Token': staffWriteCredential(),
  };
  if (assertion) {
    headers['X-Catalog-Organizer-Assertion'] = assertion;
  }
  return headers;
}

// A READ scoped by an explicit organizer parameter — not authorization.
//
// `organizerId` here is a filter on a PUBLIC endpoint, and it stays a required
// parameter (TKT-245 removed its default, which was a hardcoded v1 organizer with
// a note saying "when admin auth lands this comes from the session" — this is that
// landing). Every caller passes the session's organizer. It carries no authority:
// the data behind it is public, and writes take their organizer from the signed
// assertion instead.
export async function getVenues(organizerId: string): Promise<Venue[]> {
  const url = `${GATEWAY_URL}/api/catalog/public/venues?organizer_id=${encodeURIComponent(organizerId)}`;
  const res = await fetch(url);
  if (!res.ok) {
    throw new Error(`catalog venue read failed: ${res.status}`);
  }
  const body = (await res.json()) as PublicVenueList;
  return body.venues;
}

/** One venue by id (v1 has no single-venue read; filter the organizer list). */
export async function getVenue(
  venueId: string,
  organizerId: string,
): Promise<Venue | undefined> {
  const venues = await getVenues(organizerId);
  return venues.find((v) => v.id === venueId);
}

const catalog = (path: string) => `${GATEWAY_URL}/api/catalog${path}`;

// parseError pulls the catalog's { error } message off a non-2xx response so the
// UI can surface it; falls back to a generic line if the body is not the shared
// Error shape. Never throws while reading the body.
async function parseError(res: Response): Promise<CatalogApiError> {
  let message = `catalog request failed: ${res.status}`;
  try {
    const body = (await res.json()) as { error?: unknown };
    if (body && typeof body.error === 'string' && body.error) {
      message = body.error;
    }
  } catch {
    // non-JSON body — keep the generic message
  }
  return new CatalogApiError(res.status, message);
}

async function postCatalog<T>(path: string, assertion: string, body: unknown): Promise<T> {
  const res = await fetch(catalog(path), {
    method: 'POST',
    headers: writeHeaders(assertion),
    body: JSON.stringify(body),
  });
  if (!res.ok) {
    throw await parseError(res);
  }
  return (await res.json()) as T;
}

// --- Seat-map authoring (US-019). Writes go through the gateway server-side,
// same posture as the reads; the browser never talks to the gateway directly. ---

export function createSeatMap(
  venueId: string,
  name: string,
  assertion: string,
  // Orphan-seat prevention (ADR-041). Defaults off so an existing caller creates
  // exactly the map it created before; the flag is per version, and an edit that
  // omits it inherits rather than clears.
  orphanPreventionEnabled = false,
): Promise<SeatMap> {
  return postCatalog<SeatMap>(`/venues/${encodeURIComponent(venueId)}/seat-maps`, assertion, {
    name,
    orphan_prevention_enabled: orphanPreventionEnabled,
  });
}

